/**
 * Universal fallback helper for entity type icon
 */
export function getEntityTypeSvg(type, classes = 'w-4 h-4') {
  switch ((type || '').toLowerCase()) {
    case 'product':
    case 'products':
      return iconPackage(classes);
    case 'category':
    case 'categories':
      return iconFolder(classes);
    case 'brand':
    case 'brands':
      return iconBuilding(classes);
    case 'badge':
    case 'badges':
      return iconTag(classes);
    case 'transfer':
    case 'transfers':
      return iconTruck(classes);
    case 'trash':
    case 'vault':
      return iconTrash(classes);
    default:
      return iconPackage(classes);
  }
}

